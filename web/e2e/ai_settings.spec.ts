import { expect, test } from '@playwright/test'

test('configure trusted models, probe a draft, keep the key hidden and reset', async ({ page }, info) => {
  await page.route('https://telegram.org/js/telegram-web-app.js', route => route.fulfill({ contentType: 'text/javascript', body: '' }))
  await page.goto('/')
  if (info.project.name === 'mobile') await page.getByRole('button', { name: 'Открыть меню' }).click()
  await page.getByRole('button', { name: /Локальный пользователь Личное пространство/ }).click()
  const dialog = page.getByRole('dialog', { name: 'Твоё пространство' })
  await dialog.getByRole('button', { name: 'Настроить модели и подключения' }).click()
  await dialog.getByRole('tab', { name: 'Доверенная LLM' }).click()
  await dialog.getByLabel('Адрес API', { exact: true }).fill('http://private-model.test/v1')
  await dialog.getByLabel('Модель ответов', { exact: true }).fill('private-answer')
  await dialog.getByLabel('Модель разбора и правок', { exact: true }).fill('private-organizer')
  await dialog.getByLabel('API-ключ', { exact: true }).fill('PRIVATE_TEST_KEY')
  await dialog.getByRole('checkbox', { name: 'Включить этот контур' }).uncheck()
  await page.route('**/api/ai-settings/trusted/test', async route => {
    const data = route.request().postDataJSON()
    expect(data.draft.chat_model).toBe('private-answer')
    expect(data.draft.organize_model).toBe('private-organizer')
    expect(data.draft.api_key).toBe('PRIVATE_TEST_KEY')
    await route.fulfill({ json: { ok: true, message: 'Тестовое соединение прошло', latency_ms: 12 } })
  })
  await dialog.getByRole('button', { name: 'Ответы', exact: true }).click()
  await expect(dialog.getByRole('status')).toContainText('Тестовое соединение прошло')
  const saved = page.waitForResponse(r => r.url().endsWith('/api/ai-settings/trusted') && r.request().method() === 'PUT')
  await dialog.getByRole('button', { name: 'Сохранить настройки моделей' }).click()
  expect(await (await saved).text()).not.toContain('PRIVATE_TEST_KEY')
  await expect(dialog.getByLabel('API-ключ', { exact: true })).toHaveValue('')
  await expect(dialog.getByLabel('API-ключ', { exact: true })).toHaveAttribute('placeholder', /Ключ задан/)
  await dialog.getByRole('button', { name: 'Перечитать настройки' }).click()
  await expect(dialog.getByLabel('Модель ответов', { exact: true })).toHaveValue('private-answer')
  await expect(dialog.getByLabel('API-ключ', { exact: true })).toHaveValue('')
  await dialog.getByRole('button', { name: 'Вернуть настройки из .env' }).click()
  await expect(dialog.getByLabel('Модель ответов', { exact: true })).toHaveValue('')
})

test('single discovered model fills empty trusted configuration and explains next step', async ({ page }, info) => {
  await page.route('https://telegram.org/js/telegram-web-app.js', route => route.fulfill({ contentType: 'text/javascript', body: '' }))
  await page.goto('/')
  if (info.project.name === 'mobile') await page.getByRole('button', { name: 'Открыть меню' }).click()
  await page.getByRole('button', { name: /Локальный пользователь Личное пространство/ }).click()
  const dialog = page.getByRole('dialog', { name: 'Твоё пространство' })
  await dialog.getByRole('button', { name: 'Настроить модели и подключения' }).click()
  await dialog.getByRole('tab', { name: 'Доверенная LLM' }).click()
  await dialog.getByLabel('Адрес API', { exact: true }).fill('https://strata.example/v1')
  await expect(dialog.getByRole('status')).toContainText('модель ещё не выбрана')
  await page.route('**/api/ai-settings/trusted/test', route => route.fulfill({ json: { ok: true, models: ['local-qwen'] } }))
  await dialog.getByRole('button', { name: 'Загрузить список моделей' }).click()
  await expect(dialog.getByLabel('Модель ответов', { exact: true })).toHaveValue('local-qwen')
  await expect(dialog.getByRole('status')).toContainText('сохраните настройки')
  await expect(dialog.getByRole('combobox', { name: 'Выбрать модель из списка' })).toHaveValue('local-qwen')
  // Discovering/selecting is a draft; it must not silently save the configuration.
  await dialog.getByRole('button', { name: 'Перечитать настройки' }).click()
  await expect(dialog.getByLabel('Модель ответов', { exact: true })).toHaveValue('')
})
