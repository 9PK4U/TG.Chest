import { expect, test } from '@playwright/test'

test.beforeEach(async ({ page }) => {
  await page.route('https://telegram.org/js/telegram-web-app.js', route => route.fulfill({ contentType: 'text/javascript', body: '' }))
})

test('create, edit, retrieve, favorite, attach and delete a note', async ({ page }, testInfo) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Все записи.' })).toBeVisible()
  const title = `Проверка заметки ${testInfo.project.name}`
  await page.getByRole('button', { name: 'Новая запись', exact: true }).click()
  let dialog = page.getByRole('dialog')
  await dialog.getByLabel('Название', { exact: true }).fill(title)
  await dialog.getByLabel('Содержимое').fill('Билеты на поезд и план путешествия в Казань.')
  await dialog.getByLabel('Теги', { exact: false }).fill('поездка, планы')
  await dialog.getByRole('button', { name: 'Сохранить', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  await expect(page.getByRole('heading', { name: title })).toBeVisible()
  await page.getByRole('button', { name: `Открыть ${title}`, exact: true }).click()
  dialog = page.getByRole('dialog')
  await dialog.getByLabel('Содержимое').fill('Билеты на поезд и план путешествия в Казань. Отъезд в пятницу.')
  await dialog.locator('input[type=file]').setInputFiles({ name: 'план.txt', mimeType: 'text/plain', buffer: Buffer.from('Гостиница у вокзала, бронирование до 18 часов.') })
  await dialog.getByRole('button', { name: 'Сохранить', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  await page.getByRole('article').filter({ has: page.getByRole('heading', { name: title }) }).getByRole('button', { name: 'В избранное', exact: true }).click()
  await expect(page.getByRole('article').filter({ has: page.getByRole('heading', { name: title }) }).getByRole('button', { name: 'Убрать из избранного' })).toBeVisible()
  await expect(async () => {
    await page.getByRole('textbox', { name: 'Поиск по сохранённому' }).fill('Билеты')
    await page.getByRole('button', { name: 'Найти', exact: true }).click()
    await expect(page.getByText(/Результаты поиска/)).toBeVisible()
    await expect(page.getByRole('heading', { name: title })).toBeVisible()
  }).toPass({ timeout: 15000 })
  await page.screenshot({ path: `../test-results/search-${testInfo.project.name}.png`, fullPage: true })
  await page.getByRole('button').filter({ has: page.getByRole('heading', { name: title }) }).click()
  dialog = page.getByRole('dialog')
  await expect(dialog.getByRole('button', { name: 'Скачать план.txt', exact: true })).toBeVisible()
  await dialog.getByRole('button', { name: 'Удалить запись', exact: true }).click()
  await dialog.getByRole('button', { name: 'Удалить', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  expect(errors).toEqual([])
})

test('master password encrypts a secret and vault locks', async ({ page }, testInfo) => {
  await page.goto('/')
  const mobile = testInfo.project.name === 'mobile'
  await (mobile ? page.getByRole('navigation', { name: 'Быстрая навигация' }) : page.getByRole('navigation', { name: 'Основная навигация' })).getByRole('button', { name: 'Сейф', exact: true }).click()
  const password = 'master password for test only'
  const setup = page.getByRole('button', { name: 'Настроить сейф', exact: true })
  const isNew = await setup.isVisible()
  await (isNew ? setup : page.getByRole('button', { name: 'Открыть сейф', exact: true })).click()
  let dialog = page.getByRole('dialog')
  await dialog.getByLabel('Мастер-пароль', { exact: true }).fill(password)
  if (isNew) {
    await dialog.getByLabel('Ещё раз').fill(password)
    await dialog.getByRole('textbox', { name: 'Подсказка к мастер-паролю', exact: true }).fill('Моя первая ассоциация')
  }
  await dialog.getByRole('button', { name: isNew ? 'Создать сейф' : 'Открыть сейф', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  await page.getByRole('button', { name: 'Подсказка к паролю', exact: true }).click()
  const hint = `Напоминание ${testInfo.project.name}`
  await page.getByRole('dialog').getByRole('textbox', { name: 'Подсказка к мастер-паролю', exact: true }).fill(hint)
  await page.getByRole('button', { name: 'Сохранить подсказку', exact: true }).click()
  await expect(page.getByRole('dialog')).not.toBeVisible()
  await page.getByRole('button', { name: 'Добавить пароль', exact: true }).click()
  dialog = page.getByRole('dialog')
  const title = `Почта ${testInfo.project.name}`
  await dialog.getByLabel('Название', { exact: true }).fill(title)
  await dialog.getByLabel('Логин', { exact: true }).fill('me@example.com')
  await dialog.getByLabel('Пароль', { exact: true }).fill('VERY_PRIVATE_SECRET')
  const sent = page.waitForRequest(r => r.url().endsWith('/api/entries') && r.method() === 'POST')
  await dialog.getByRole('button', { name: 'Сохранить', exact: true }).click()
  expect((await sent).postData()).not.toContain('VERY_PRIVATE_SECRET')
  expect((await sent).postData()).not.toContain('me@example.com')
  await expect(dialog).not.toBeVisible()
  await page.getByRole('button', { name: `Открыть ${title}`, exact: true }).click()
  dialog = page.getByRole('dialog')
  await expect(dialog.getByLabel('Пароль', { exact: true })).toHaveValue('VERY_PRIVATE_SECRET')
  await dialog.getByRole('button', { name: 'Закрыть', exact: true }).click()
  await page.getByRole('button', { name: 'Закрыть сейф', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Открыть сейф', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Открыть сейф', exact: true }).click()
  await expect(page.getByRole('dialog').locator('.vault-hint')).toContainText(hint)
  await page.getByRole('dialog').getByLabel('Мастер-пароль', { exact: true }).fill(password)
  await page.getByRole('dialog').getByRole('button', { name: 'Открыть сейф', exact: true }).click()
  await page.getByRole('button', { name: `Открыть ${title}`, exact: true }).click()
  await expect(page.getByRole('dialog').getByLabel('Пароль', { exact: true })).toHaveValue('VERY_PRIVATE_SECRET')
  await page.getByRole('dialog').getByRole('button', { name: 'Закрыть', exact: true }).click()
  await page.getByRole('button', { name: 'Закрыть сейф', exact: true }).click()
  await page.screenshot({ path: `../test-results/vault-${testInfo.project.name}.png`, fullPage: true })
})
